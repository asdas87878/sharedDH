def shell_rows():
    parts = json.load(open(os.path.join(ROOT, "art", "map", "hub_study", "S_f", "parts.json")))["parts"]
    rows = []
    for p in parts:
        x, _, z = p["p"]
        if p["k"] in ("prop", "far", "water", "barrier", "figure", "station") or p["n"] == "DockSpawn" or p["n"].startswith("Plot"):
            continue
        if abs(x) > 420 or z > 420 or z < -420:
            continue
        pic = {"ground": 1, "plain": 1, "hub": 1, "face": 3, "grass": 4, "fill": 1}.get(p["k"], 0)
        tex = p.get("tex", {})
        row = {"n": p["n"], "p": [round(x + X, 2), round(p["p"][1], 2), round(z, 2)], "s": [max(0.05, v) for v in p["s"]], "c": p["c"],
               "x": [round(v, 4) for v in p["x"]], "y": [round(v, 4) for v in p["y"]], "solid": bool(p["solid"]),
               "shadow": p["k"] not in ("trim", "ground", "hub", "core", "fill", "glow")}
        if pic in (1, 4):
            row["top"] = tex.get("top", [0, 0, 0, 0])
        if pic in (3, 4):
            row["side"] = tex.get("side", [0, 0, 0, p.get("v", 0)])
        rows.append(row)
    return rows


def pens(out):
    for i, ((x0, x1, z0, z1), (gx, gz, dx, dz)) in enumerate(zip(plan.s_pens, plan.s_gates)):
        cx, cz = (x0 + x1) / 2, (z0 + z1) / 2
        # the pen's own frame: its gate on +z. A side pen is 60 wide along the wall and 50 deep
        yaw = 0 if dz else (90 if dx > 0 else -90)
        pl.W, pl.D = (x1 - x0, z1 - z0) if dz else (z1 - z0, x1 - x0)
        k = Kit(out, "S/Pen%d" % (i + 1), (cx, hub_kit.FLOOR_Y, cz), yaw)
        along = k._dir((1, 0, 0))
        pl.GATE_AT = (gx - cx) * along[0] + (gz - cz) * along[2]
        pl.pb.plate(k, -pl.W / 2, pl.W / 2, -pl.D / 2, pl.D / 2, SAND)
        before = len(out)
        pl.PENS[STYLE](k, -pl.W / 2, pl.W / 2, STAGE[i])
        board = [p for p in out[before:] if p["n"] == "SignBoard"][0]["p"]
        off = math.hypot(board[0] - gx, board[2] - gz)
        assert off < 2, ("pen", i + 1, "its gate is", off, "studs off its place")
    pl.W, pl.D, pl.GATE_AT = 50.0, 60.0, 0.0


def stations(out):
    hub = json.load(open(os.path.join(ROOT, "art", "map", "greybox", "hub.json")))
    for tx, tz, tw, _td, label, colour in plan.s_things:
        if tw == 12 and not label:
            Kit(out, "S/Pads", (tx, hub_kit.FLOOR_Y, tz)).box(0, 0, 0, 12, 0.6, 12, colour, n="Pad", solid=False, shadow=False)
            continue
        name = label or "Earners"
        mine = [p for p in hub["parts"] if p["m"] == "Stations/" + name or p["m"].startswith("Stations/" + name + "/")]
        body = [p for p in mine if "s" in p and not p.get("bill")]
        cx = (min(p["p"][0] for p in body) + max(p["p"][0] for p in body)) / 2
        cz = (min(p["p"][2] for p in body) + max(p["p"][2] for p in body)) / 2
        for p in mine:
            p = {a: b for a, b in p.items() if a != "circle"}  # its floor ring is tagged, and the game reads the tag
            if p.get("tex") == "ripple":
                del p["tex"]
            out.append(dict(p, m="S/" + name, p=[p["p"][0] - cx + tx, p["p"][1], p["p"][2] - cz + tz]))


def rows(out):
    for stage in range(6):  # the pick, stage 0 to 5 in a row
        k = Kit(out, "Rows/E%d" % stage, (ROWS_AT + (stage - 2.5) * 56, hub_kit.FLOOR_Y, -165))
        pl.pb.plate(k, -25, 25, -30, 30, SAND)
        pl.pen_e(k, -25, 25, stage)


def main():
    os.makedirs(OUT, exist_ok=True)
    for old in os.listdir(OUT):
        os.remove(os.path.join(OUT, old))
    rs = shell_rows()
    size = 300
    n = -(-len(rs) // size)
    for i in range(n):
        text = SHELL.replace("{K}", str(i + 1)).replace("{N}", str(n)).replace("{TILE}", TILE)
        text = text.replace("{ROWS}", json.dumps(rs[i * size:(i + 1) * size], separators=(",", ":")))
        open(os.path.join(OUT, "%02d_shell.luau" % (i + 1)), "w", encoding="utf-8", newline="\n").write(text)
    out = []
    pens(out)
    stations(out)
    rows(out)
    json.dump({"parts": out, "feet": {}, "floor": [ROWS_AT, 0, -120, 400, 260]}, open(os.path.join(hub_kit.BOX, "hub_try.json"), "w"))
    # for a picture without Studio: HUB_JSON=hub_try_view.json hub_view.py -- S <out> <shot>
    shell = [{"m": "S/Shell", "n": r["n"], "p": [r["p"][0] - X, r["p"][1], r["p"][2]], "x": r["x"], "y": r["y"], "s": r["s"], "c": r["c"], "f": 3} for r in rs if r["n"] != "HubFloor"]
    view = {"parts": out + shell, "feet": {"S": [[0, 0, 0], [1, 0, 0], [0, 1, 0]]}}
    json.dump(view, open(os.path.join(hub_kit.BOX, "hub_try_view.json"), "w"))
    tmp = os.path.join(OUT, "kit")
    os.makedirs(tmp, exist_ok=True)
    env = dict(os.environ, HUB_BENCH="1", HUB_BENCH_JSON="hub_try.json")
    subprocess.run([sys.executable, os.path.join(ROOT, "tools", "map", "hub_luau.py"), tmp, str(X)], check=True, env=env)
    for f in sorted(os.listdir(tmp)):
        text = open(os.path.join(tmp, f), encoding="utf-8").read().replace("ClaudeHubBench", "HubTryPens")
        text = text.replace("--!nocheck\n", '--!nocheck\nassert(not game:GetService("RunService"):IsRunning(), "Studio is in Play")\n', 1)
        open(os.path.join(OUT, "5" + f), "w", encoding="utf-8", newline="\n").write(text)
        os.remove(os.path.join(tmp, f))
    os.rmdir(tmp)
    print(len(rs), "shell parts,", len(out), "kit pieces;", sorted(os.listdir(OUT)))


if __name__ == "__main__":
    main()
