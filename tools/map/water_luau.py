"""Writes the Studio installer for the moving water (docs/design/water.md): tools/studio/greybox/98_water.luau, which
puts tools/map/water_look.luau into the map as a client script, ClaudeBlockout.Surface.WaterLook. Run it after the
map's own loader files (it is numbered to sort after them and before the check):
    python tools/map/water_luau.py
    node tools/studio/run_luau.js <studio_id> tools/studio/greybox/98_water.luau
The water shows when the game is played: the script builds it on the player's own machine."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import json
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from water_zones import ZONES  # noqa: E402

source = open(os.path.join(ROOT, "tools", "map", "water_look.luau"), encoding="utf-8").read()
# the lands' water and the lane's line, baked in from the map as it was built (the map sits 3,000 studs along X)
info = json.load(open(os.path.join(ROOT, "art", "map", "greybox", "path.json")))
starts = [land["S0"] for land in info["Lands"]]


def c3(c):
    return f"Color3.fromRGB({c[0]}, {c[1]}, {c[2]})"


zones = ",\n\t".join("{ %g, %s, %d, %s, %g, %g, %s, %g, %s }" % (s0, c3(z["water"]), z["see"], c3(z["tint"]), z["vivid"], z["shafts"], c3(z["specks"]),
                                                                    z["thick"], c3(z["ceiling"]))
                       for s0, z in zip(starts, ZONES))
line = ",\n\t".join(", ".join("{ %g, %g, %g }" % (r[1] + 3000, r[3], r[0]) for r in info["Path"][k:k + 6]) for k in range(0, len(info["Path"]), 6))
assert "--ZONES--" in source and "--LINE--" in source
source = source.replace("--ZONES--", zones).replace("--LINE--", line)
assert "]==]" not in source
MESH = "rbxassetid://446556804"  # a plain cube from the Creator Store ("Smooth Cube", asset 446556868, free). The
# creatures' own box meshes were tried first: they are painted dark, and a mesh's paint darkens everything, foam included
out = '''--!nocheck
-- Generated by tools/map/water_luau.py from tools/map/water_look.luau: do not edit by hand.
local surface = workspace:FindFirstChild("ClaudeBlockout") and workspace.ClaudeBlockout:FindFirstChild("Surface")
assert(surface, "the map isn't loaded: run the grey-box loader first")
for _, old in surface:GetChildren() do
	if old.Name == "WaterLook" then
		old:Destroy()
	end
end
local layers = surface:FindFirstChild("WaterLayers") -- left by a look in Edit mode: they don't survive a save
if layers then
	layers:Destroy()
end
for _, sea in surface:GetChildren() do
	if sea:IsA("BasePart") and sea.Name == "SeaTile" then
		sea.Transparency = 0.35
	end
end
local s = Instance.new("Script")
s.Name = "WaterLook"
s.RunContext = Enum.RunContext.Client
s.Source = [==[%s]==]
-- the box mesh the layers are copies of: a plain unpainted cube from the Creator Store
local slab = game:GetService("AssetService"):CreateMeshPartAsync(Content.fromUri("%s"))
slab.Name, slab.Anchored, slab.CanCollide, slab.Size = "Slab", true, false, Vector3.new(4, 0.4, 4)
local kit = surface:FindFirstChild("WaterKit")
if kit then
	kit:Destroy()
end
kit = Instance.new("Model")
kit.Name = "WaterKit"
kit.ModelStreamingMode = Enum.ModelStreamingMode.Persistent -- so the mesh reaches every player wherever they are
slab.Transparency = 1
slab.Position = Vector3.new(3000, -30, -128) -- out of sight inside the hub's floor
slab.Parent = kit
kit.Parent = surface
s.Parent = surface
return "WaterLook installed in " .. surface:GetFullName() .. " (" .. #s.Source .. " characters): press Play to see it"
''' % (source, MESH)
path = os.path.join(ROOT, "tools", "studio", "greybox", "98_water.luau")
open(path, "w", encoding="utf-8", newline="").write(out)
print("written", path)
