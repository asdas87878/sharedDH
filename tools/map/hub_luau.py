"""Turns the hub's models (tools/map/hub_kit.py: art/map/greybox/hub.json) into Luau files that build them in Studio,
under Workspace.ClaudeBlockout.Dock. They run after the map's parts files and before the water (load_greybox.py), or
by themselves, to change only the hub: a few seconds where the whole map takes twenty-five minutes.

usage: python tools/map/hub_kit.py && python tools/map/hub_luau.py
       for f in tools/studio/greybox/9?_hub.luau; do node tools/studio/run_luau.js <studio_id> "$f"; done

What they build:
  Dock/Stations/<Sell, Auras, Fuse, Index, Sub, Earners>   a Model each; PrimaryPart is Ring (the coloured ring on the
                                    floor in front: where a player stands to use it; Earners has none); Title carries
                                    the name floating over it (a BillboardGui)
  Dock/Stations/Earners/Board       its SurfaceGui "Rows" holds Row1 ... Row5 (TextLabels) for the game to write on
  Dock/Gate                         the arch, its sign, the kelp
  Dock/Plots/Plot1 ... Plot8        a Model each, with the parts the game reads by name: TankWater, Pad,
                                    SignBoard, TrainerSpot, UpgradeBoard and UpgradePost (the seahorse's upgrade sign);
                                    TrainerRide is a Model (the seahorse) whose PrimaryPart is the part named TrainerRide
  Dock/Landmark, Dock/Dressing
  Dock/HubLife                      a small client script: the water on the tanks and pools moves
The first file clears what the last run made (and the blockout's stalls and flags, if this map still has them)."""
